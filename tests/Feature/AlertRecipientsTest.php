<?php

namespace Tests\Feature;

use App\Models\Alert;
use App\Models\Campus;
use App\Models\Incident\Incident;
use App\Models\Personnel;
use App\Services\Sms\SmsGatewayInterface;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Support\Facades\Hash;
use Tests\Concerns\ReadsReportHtml;
use Tests\TestCase;

/**
 * Send Alert: the Admin sending it is not texted, and each alert keeps who it
 * went to — name, role and number as they were — on the Send Alert page,
 * in Alert History and in its PDF.
 */
class AlertRecipientsTest extends TestCase
{
    use ReadsReportHtml, RefreshDatabase;

    protected Campus $campus;

    protected Personnel $admin;

    /** @var list<string> numbers the gateway was asked to text */
    protected array $texted = [];

    protected function setUp(): void
    {
        parent::setUp();
        $this->campus = Campus::create(['campus_name' => 'ASCOT Zabali Campus']);
        $this->admin = $this->person('Alert Admin', 'DRRMO Admin', '09171110000');
        $test = $this;
        $this->app->instance(SmsGatewayInterface::class, new class($test) implements SmsGatewayInterface
        {
            public function __construct(private $test) {}

            public function send(string $phoneNumber, string $message): bool
            {
                $this->test->recordText($phoneNumber);

                return $phoneNumber !== '639175550000'; // the gateway refuses this one
            }
        });
    }

    public function recordText(string $number): void
    {
        $this->texted[] = $number;
    }

    protected function person(string $name, string $role, ?string $phone, ?Campus $campus = null): Personnel
    {
        $person = Personnel::create(['campus_id' => ($campus ?? $this->campus)->campus_id, 'full_name' => $name, 'role' => $role,
            'email' => strtolower(str_replace(' ', '.', $name)) . '@ascot-test.local', 'password_hash' => Hash::make('password'), 'contact_number' => $phone]);
        $person->forceFill(['is_approved' => true])->save();

        return $person;
    }

    public function test_the_sender_is_left_out_and_every_recipient_is_kept_with_the_alert(): void
    {
        $coordinator = $this->person('Carla Coordinator', 'Coordinator', '09172223333');
        $this->person('Rico Reporter', 'Reporter', '09175550000'); // the gateway refuses it
        $this->person('Landline Lito', 'Reporter', '074-123-4567'); // not a mobile number
        $this->person('No Number Nora', 'Coordinator', null);
        $this->person('Other Campus Oscar', 'Coordinator', '09179990000', Campus::create(['campus_name' => 'ASCOT Bazal Campus']));
        // Another Admin: no campus of their own, so not a campus recipient.
        $otherAdmin = $this->person('Second Admin', 'DRRMO Admin', '09174440000');
        $incident = Incident::forceCreate(['campus_id' => $this->campus->campus_id, 'hazard_type' => 'Fire', 'date_occurred' => '2026-10-22', 'status' => 'Active']);

        // Before sending: the list, without the sender.
        $page = $this->actingAs($this->admin)->get(route('admin.incidents.alerts.create', $incident))->assertOk()
            ->assertSee('Who will receive it (3)')->assertSee('Carla Coordinator')->assertSee('09172223333')
            ->assertDontSee('No Number Nora')->assertDontSee('Other Campus Oscar');
        // (The sender's own name is on the page anyway, as the signed-in user.)
        $this->assertSame(['Carla Coordinator', 'Landline Lito', 'Rico Reporter'], $page->viewData('recipients')->pluck('full_name')->all());

        $this->post(route('admin.incidents.alerts.store', $incident), ['message' => 'Fire at the gym. Evacuate now.'])->assertRedirect();

        $this->assertNotContains('639171110000', $this->texted, 'the sender is not texted');
        $this->assertEqualsCanonicalizing(['639172223333', '639175550000'], $this->texted);

        $alert = Alert::firstOrFail();
        $this->assertSame(3, $alert->recipient_count);
        $this->assertSame('Partial', $alert->delivery_status);
        $this->assertSame([
            ['Carla Coordinator', 'Coordinator', '09172223333', 'Sent'],
            ['Landline Lito', 'Reporter', '074-123-4567', 'Skipped'],
            ['Rico Reporter', 'Reporter', '09175550000', 'Failed'],
        ], $alert->recipients->map(fn ($r) => [$r->full_name, $r->role, $r->contact_number, $r->status])->all());

        // Alert History and the PDF name them.
        $this->get(route('admin.incidents.show', $incident))->assertOk()->assertSee('Carla Coordinator')->assertSee('09175550000');
        // Downloaded by the other Admin: the header's "Generated by" names whoever downloads it.
        $pdf = $this->reportText($this->capturePdf($otherAdmin, 'reports.records.alert', route('admin.incidents.alerts.report', [$incident, $alert]))['html']);
        foreach (['Recipients', 'Carla Coordinator', '09172223333', 'Rico Reporter', 'Failed', 'Landline Lito', 'Skipped'] as $text) {
            $this->assertStringContainsString($text, $pdf);
        }
        $this->assertStringNotContainsString('Alert Admin', $pdf);

        // A deleted account stays on the list as it was.
        $this->actingAs($otherAdmin);
        $coordinator->delete();
        $this->assertSame('Carla Coordinator', $alert->recipients()->where('full_name', 'Carla Coordinator')->value('full_name'));
        $this->assertNull($alert->recipients()->where('full_name', 'Carla Coordinator')->value('personnel_id'));
    }

    public function test_an_alert_sent_before_recipients_were_kept_still_shows_and_prints(): void
    {
        $incident = Incident::forceCreate(['campus_id' => $this->campus->campus_id, 'hazard_type' => 'Flood', 'date_occurred' => '2026-10-01', 'status' => 'Resolved']);
        $alert = Alert::create(['incident_id' => $incident->incident_id, 'message' => 'Old alert', 'sent_at' => '2026-10-01 10:00:00', 'recipient_count' => 12, 'delivery_status' => 'Sent']);

        $this->actingAs($this->admin)->get(route('admin.incidents.show', $incident))->assertOk()->assertSee('Old alert');
        $pdf = $this->reportText($this->capturePdf($this->admin, 'reports.records.alert', route('admin.incidents.alerts.report', [$incident, $alert]))['html']);
        $this->assertStringContainsString('Not recorded: this alert was sent before recipients were kept.', $pdf);
    }
}
